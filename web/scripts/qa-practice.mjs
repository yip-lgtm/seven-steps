import { chromium } from "playwright";
const browser = await chromium.launch({ args: ["--no-sandbox"] });
const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
page.on("console", (m) => {
  if (m.type() === "error") console.log("CONSOLE", m.text());
});
page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
await page.goto("http://127.0.0.1:8080/", { waitUntil: "networkidle" });
await page.waitForTimeout(2500);
await page.screenshot({ path: "/workspace/screenshots/home-after-fetch.png" });
const banner = await page.locator("body").innerText();
console.log("BANNER_SNIP", banner.slice(0, 500).replace(/\n/g, " | "));
await page.getByRole("button", { name: /開始今日|Start today|繼續今日|Continue today|接回練習|Resume practice/ }).click();
await page.waitForTimeout(800);
await page.screenshot({ path: "/workspace/screenshots/practice-rate.png" });
const stars = page.getByRole("radio");
await stars.nth(3).click();
await page.waitForTimeout(300);
await page.getByRole("button", { name: /下一步|Next step/ }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: "/workspace/screenshots/practice-grasp.png" });
await page.goto("http://127.0.0.1:8080/settings");
await page.waitForTimeout(500);
await page.screenshot({ path: "/workspace/screenshots/settings.png" });
await page.goto("http://127.0.0.1:8080/login");
await page.waitForTimeout(400);
await page.screenshot({ path: "/workspace/screenshots/login.png" });
await browser.close();
console.log("DONE");
