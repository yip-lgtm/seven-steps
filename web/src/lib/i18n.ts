export type StrKey = Exclude<keyof (typeof STR)["zh"], "rateLabels">;

export function t(
  lang: Lang,
  key: StrKey,
  vars?: Record<string, string | number>,
): string {
  let s = String(STR[lang][key] ?? STR.en[key] ?? key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}

export function rateLabels(lang: Lang): readonly string[] {
  return STR[lang].rateLabels;
}

